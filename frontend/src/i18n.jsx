const LangCtx = createContext({ lang: 'vi', setLang: () => {} })

function storedLang() {
  try {
    const v = localStorage.getItem('hh_lang')
    if (v === 'en' || v === 'vi') return v
  } catch { /* storage blocked */ }
  return 'vi'
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(storedLang)
  const setLang = useCallback((l) => {
    setLangState(l)
    try { localStorage.setItem('hh_lang', l) } catch { /* ignore */ }
  }, [])
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  return <LangCtx.Provider value={{ lang, setLang }}>{children}</LangCtx.Provider>
}

export function format(str, vars) {
  if (!vars) return str
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''))
}

// Like t(), but {n} can be a React element (e.g. an animated number) and the
// sentence keeps its own word order in each language.
export function tNodeFor(lang) {
  return (key, vars) => {
    const str = STRINGS[lang][key] ?? STRINGS.en[key] ?? key
    return str.split(/(\{\w+\})/).map((part, i) => {
      const m = part.match(/^\{(\w+)\}$/)
      return m ? <span key={i}>{vars?.[m[1]]}</span> : part
    })
  }
}

export function tFor(lang) {
  return (key, vars) => format(STRINGS[lang][key] ?? STRINGS.en[key] ?? key, vars)
}

export function useLang() {
  const { lang, setLang } = useContext(LangCtx)
  const other = lang === 'vi' ? 'en' : 'vi'
  return { lang, other, setLang, t: tFor(lang), t2: tFor(other), tn: tNodeFor(lang) }
}

// Pick the right language from a {en, vi} content object.
export function pick(obj, lang) {
  if (!obj) return ''
  if (typeof obj === 'string') return obj
  return obj[lang] ?? obj.en ?? ''
}
